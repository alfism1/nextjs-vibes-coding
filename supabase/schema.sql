-- Create the flights table
create table public.flights (
  id uuid default gen_random_uuid() primary key,
  flight_number text not null,
  start_time timestamptz not null,
  end_time timestamptz not null,
  time_zone text not null,
  start_location text not null,
  end_location text not null,
  created_at timestamptz default now()
);

-- Enable Row Level Security (RLS)
alter table public.flights enable row level security;

-- Create a policy that allows anyone to read flights (public access)
create policy "Enable read access for all users"
on public.flights
for select
to public
using (true);

-- Create a policy that allows anyone to insert/update/delete (FOR DEMO/ADMIN ONLY)
-- IN PRODUCTION: You should restrict this to authenticated users with specific roles
create policy "Enable write access for all users"
on public.flights
for all
to public
using (true)
with check (true);

-- Custom types
create type public.app_role as enum ('admin', 'moderator');

-- USER ROLES
create table public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null,
  role app_role not null,
  unique (user_id, role)
);
comment on table public.user_roles is 'Application roles for each user.';

-- Create the auth hook function
create or replace function public.custom_access_token_hook(event jsonb)
returns jsonb
language plpgsql
stable
as $$
  declare
    claims jsonb;
    user_role public.app_role;
  begin
    -- Fetch the user role in the user_roles table
    select role into user_role from public.user_roles where user_id = (event->>'user_id')::uuid;

    claims := event->'claims';

    if user_role is not null then
      -- Set the claim
      claims := jsonb_set(claims, '{user_role}', to_jsonb(user_role));
    else
      claims := jsonb_set(claims, '{user_role}', 'null');
    end if;

    -- Update the 'claims' object in the original event
    event := jsonb_set(event, '{claims}', claims);

    -- Return the modified or original event
    return event;
  end;
$$;

grant usage on schema public to supabase_auth_admin;
grant execute on function public.custom_access_token_hook to supabase_auth_admin;
revoke execute on function public.custom_access_token_hook from authenticated, anon, public;

grant all on table public.user_roles to supabase_auth_admin;
revoke all on table public.user_roles from authenticated, anon, public;

create policy "Allow auth admin to read user roles" ON public.user_roles
as permissive for select
to supabase_auth_admin
using (true)


create policy "Allow authenticated users to read their own roles" ON public.user_roles
as permissive for select
to authenticated
using (auth.uid() = user_id);
